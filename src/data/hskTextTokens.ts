/** Source-aligned annotations; punctuation and blanks never consume a syllable. */
export interface HskTextToken {
  hanzi: string;
  pinyin?: string;
  kind?: "blank";
}
const w = (hanzi: string, pinyin?: string): HskTextToken => ({ hanzi, pinyin });
const blank = (pinyin?: string, trailing = ""): HskTextToken => ({
  hanzi: `（　）${trailing}`,
  pinyin,
  kind: "blank",
});
