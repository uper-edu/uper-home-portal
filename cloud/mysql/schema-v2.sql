CREATE TABLE IF NOT EXISTS cms_collections (
 name VARCHAR(100) PRIMARY KEY, revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
 items JSON NOT NULL, updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cms_media (
 id CHAR(64) PRIMARY KEY, mime VARCHAR(100) NOT NULL, content MEDIUMBLOB NOT NULL,
 uploaded_by VARCHAR(191) NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS site_submissions (
 id VARCHAR(191) PRIMARY KEY, kind VARCHAR(32) NOT NULL, request_id VARCHAR(191) NOT NULL,
 input_hash CHAR(64) NOT NULL, visitor_id VARCHAR(191), lead_id VARCHAR(191),
 payload JSON NOT NULL, attachment MEDIUMBLOB, attachment_name VARCHAR(191),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE submission_request(kind,request_id), FOREIGN KEY(lead_id) REFERENCES portal_leads(id)
) ENGINE=InnoDB;
